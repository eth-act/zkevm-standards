#!/usr/bin/env bash
# Generate the Lean model from the patched sail-riscv with the reference base config,
# then build it and the zkvm-ref Lean package.
#
# Only the I and M instruction modules (plus everything `postlude` requires) are generated.
# With all modules, the `instruction` type has 355 constructors, beyond the Lean runtime's
# constructor-tag limit (so `execute` cannot be compiled), and elaborating the 32-bit decoder
# does not finish in hours. The base config enables no other instruction extension, so the
# omitted encodings decode as illegal instructions in both this model and the C++ emulator.
# Requires reference/build/sail-riscv (scripts/prepare-sail.sh or scripts/build-emulator.sh).
set -euo pipefail
REF="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
"$REF/scripts/fetch-sail.sh"
export PATH="$REF/build/sail-0.20.2/sail/bin:$PATH"
mkdir -p "$REF/build/lean"
(
  cd "$REF/build/sail-riscv/model"
  sail --strict-var --strict-bitvector --strict-exponentials --require-version 0.20.2 \
    --memo-z3-path "$REF/build/lean/sail_smt_cache" \
    --config "$REF/config/zkvm-ref-base.json" \
    --lean --memo-z3 --lean-output-dir "$REF/build/lean" --lean-force-output \
    --lean-non-beq-type instruction --lean-non-beq-type ExecutionResult --lean-non-beq-type Step \
    --lean-import-file ../handwritten_support/RiscvExtrasExecutable.lean \
    -o Lean_RV64D_executable riscv.sail_project I_insts M_insts postlude
)
GEN="$REF/build/lean/Lean_RV64D_executable"
# Sail 0.20.2's Lean backend does not wrap the generated definitions in a `<Module>.Defs`
# namespace, which sail-riscv's handwritten support file opens; drop that `open`.
sed -i '/^open LeanRV64DExecutable\.Defs$/d' "$GEN/LeanRV64DExecutable/RiscvExtrasExecutable.lean"
# `reset` calls `cancel_reservation`, which the handwritten support file leaves as
# `panic "TODO"`. Reservations only exist for the A extension, which is not in this model,
# so cancelling one is a no-op.
sed -i 's/^def cancel_reservation : Unit → SailM Unit := λ _ => panic "TODO"$/def cancel_reservation : Unit → SailM Unit := λ _ => pure ()/' \
  "$GEN/LeanRV64DExecutable/RiscvExtrasExecutable.lean"
grep -q '^def cancel_reservation : Unit → SailM Unit := λ _ => pure ()$' \
  "$GEN/LeanRV64DExecutable/RiscvExtrasExecutable.lean"
# The generated model leaves registers without a Sail initialiser out of the state, and reading
# one throws; ZkvmRef.Machine fills them with `default` (zero), as the C++ emulator does.
# Enumerate the generated `Register` type for it.
{
  echo "-- Generated by scripts/build-lean.sh from the generated Register type. Do not edit."
  echo "import LeanRV64DExecutable"
  echo
  echo "namespace ZkvmRef"
  echo
  echo "/-- Every register of the generated model. -/"
  echo "def allRegisters : List Register := ["
  awk '/^inductive Register : Type where/{f=1;next} f&&/^  \| /{printf "%s  Register.%s", sep, $2; sep=",\n"; next} f{exit}' \
    "$GEN/LeanRV64DExecutable/Defs.lean"
  echo "]"
  echo
  echo "/-- The zero value of each register. -/"
  echo "def registerDefault : (r : Register) → RegisterType r"
  awk '/^inductive Register : Type where/{f=1;next} f&&/^  \| /{print "  | ." $2 " => default"; next} f{exit}' \
    "$GEN/LeanRV64DExecutable/Defs.lean"
  echo
  echo "end ZkvmRef"
} > "$REF/lean/ZkvmRef/RegisterDefaults.lean"
cp "$GEN/lean-toolchain" "$REF/lean/lean-toolchain"
toolchain="$(cat "$REF/lean/lean-toolchain")"
elan toolchain list | grep -q "^${toolchain}" || elan toolchain install "$toolchain"
(cd "$GEN" && lake update && lake build)
(cd "$REF/lean" && lake build)
